def get_event_schema(event_type: str) -> Optional[Dict[str, Any]]:
    """Get the schema for a canonical event."""
    event = CANONICAL_EVENTS.get(event_type)
    return event.get("schema") if event else None


def is_canonical_event(event_type: str) -> bool:
    """Check if event type is canonical."""
    return event_type in CANONICAL_EVENTS


def list_canonical_events() -> List[str]:
    """List all canonical event types."""
    return list(CANONICAL_EVENTS.keys())


def get_canonical_event_info(event_type: str) -> Optional[Dict[str, Any]]:
    """Get full info about a canonical event."""
    return CANONICAL_EVENTS.get(event_type)
