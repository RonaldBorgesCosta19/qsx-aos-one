"""
12 Canonical Event Definitions for QSX-AOS ONE.

These are the immutable contracts that define the entire decision pipeline:

1. MarketDataReceived - Raw market data from exchange
2. FeatureCalculated - Computed features from market data
3. RegimeDetected - Market regime classification
4. AlphaGenerated - Alpha signal generated by swarm/registry
5. SignalGenerated - Trading signal ready for execution
6. RiskCheckRequested - Signal sent to Risk Governor
7. RiskApproved - Risk Governor approves execution
8. RiskRejected - Risk Governor vetoes execution
9. SimulatedOrderSubmitted - Paper order submitted
10. PaperFill - Simulated order filled
11. PositionUpdated - Portfolio position updated
12. PnLUpdated - P&L recalculated
+ HealthStatusChanged - System health status change (audit event)
"""

from typing import Dict, Any, Optional, List
